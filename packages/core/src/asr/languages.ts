export const LANGUAGE_NAMES: readonly string[] = [...LANGUAGES.values()];

/**
 * The code Whisper wants for what someone typed, a code or a name in any case. An empty string
 * means let the model guess; null means Whisper would refuse it.
 */
export function whisperLanguage(input: string): string | null {
  const wanted = input.trim().toLowerCase();
  if (!wanted) return '';
  if (LANGUAGES.has(wanted)) return wanted;
  return BY_NAME.get(wanted) ?? null;
}
